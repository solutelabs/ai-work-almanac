-- Can run inside a shared database, so everything lives in its own schema. The schema isn't
-- exposed through the host's API (Supabase, for example), and tracker_app can reach nothing outside it.
CREATE SCHEMA tracker;
REVOKE ALL ON SCHEMA tracker FROM PUBLIC;

CREATE TABLE tracker.developers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  token_hash TEXT NOT NULL UNIQUE,
  created_at TEXT NOT NULL,
  revoked_at TEXT
);

CREATE TABLE tracker.machines (
  developer_id BIGINT NOT NULL REFERENCES tracker.developers(id),
  machine TEXT NOT NULL,
  os TEXT,
  version TEXT,
  last_seen TEXT NOT NULL,
  files_parsed BIGINT NOT NULL DEFAULT 0,
  parse_errors BIGINT NOT NULL DEFAULT 0,
  bad_lines BIGINT NOT NULL DEFAULT 0,
  unrecognized_files BIGINT NOT NULL DEFAULT 0,
  skipped_unresolved BIGINT NOT NULL DEFAULT 0,
  skipped_other_org BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY (developer_id, machine)
);

-- Rows hold absolute totals per log file, so a collector can safely re-send them.
CREATE TABLE tracker.usage (
  developer_id BIGINT NOT NULL REFERENCES tracker.developers(id),
  machine TEXT NOT NULL,
  tool TEXT NOT NULL,
  source TEXT NOT NULL,
  session TEXT NOT NULL,
  day TEXT NOT NULL,
  model TEXT NOT NULL,
  repo TEXT NOT NULL,
  lines_added BIGINT,   -- NULL means the tool doesn't record lines, which is not the same as zero
  lines_removed BIGINT,
  input_tokens BIGINT NOT NULL,
  output_tokens BIGINT NOT NULL,
  cache_read_tokens BIGINT NOT NULL,
  cache_write_tokens BIGINT NOT NULL,
  PRIMARY KEY (developer_id, machine, source, day, model, repo)
);
CREATE INDEX usage_day ON tracker.usage(day);

CREATE TABLE tracker.git_activity (
  month TEXT NOT NULL,
  repo TEXT NOT NULL,
  person TEXT NOT NULL,
  commits BIGINT NOT NULL,
  claude_commits BIGINT NOT NULL,
  lines_added BIGINT NOT NULL,
  lines_removed BIGINT NOT NULL,
  claude_lines_added BIGINT NOT NULL,
  synced_at TEXT NOT NULL,
  PRIMARY KEY (month, repo, person)
);

-- The login password is set separately so it never lands in this file. See the README.
CREATE ROLE tracker_app NOLOGIN CONNECTION LIMIT 10;
ALTER ROLE tracker_app SET statement_timeout = '20s';
GRANT USAGE ON SCHEMA tracker TO tracker_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA tracker TO tracker_app;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA tracker TO tracker_app;
